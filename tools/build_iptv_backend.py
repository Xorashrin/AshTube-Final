#!/usr/bin/env python3
"""
Extract a curated subset of working IPTV streams from the validated m3u,
deduplicate by channel name (one entry per channel — best quality wins),
and emit a TypeScript data file ready to embed in the MythTube app.
"""
import json
import re
import os
from urllib.parse import urlparse

SRC = "/home/z/my-project/download/iptv_working.m3u"
OUT = "/home/z/my-project/workspace/MythTube-main/src/data/iptv.ts"

# Per-category caps (to keep the app bundle small but representative)
CAPS = {
    "Movies":         50,
    "Series":         40,
    "Adult":          20,
    "Kids":           40,
    "Cartoon":        40,
    "Anime":          20,
    "Football":       20,
    "Cricket":         5,
    "Sports":         50,
    "News":           60,
    "Music":          50,
    "Entertainment":  50,
    "Documentary":    30,
    "Education":      20,
    "General":        60,
}

COUNTRY_ORDER = {"Bangladesh": 0, "India": 1, "International": 2}

# Quality scoring — higher = better
def quality_score(url: str, name: str) -> int:
    score = 0
    n = name.lower()
    u = url.lower()
    if "1080" in n: score += 80
    if "720" in n or "hd" in n: score += 40
    if "4k" in n: score += 100
    if "1080" in u or "1080p" in u: score += 60
    if "hd" in u: score += 30
    if "akamaized" in u or "cloudfront" in u or "amagi" in u: score += 25  # CDN
    if "wurl" in u: score += 20
    if url.startswith("https"): score += 15
    if "test" in n: score -= 50
    if "not 24/7" in n: score -= 30
    if "geo-blocked" in n: score -= 20
    return score

EXTINF_RE = re.compile(r'^#EXTINF:(?P<dur>-?\d+(?:\.\d+)?)(?P<attrs>.*?),\s*(?P<name>.*)$')
ATTR_RE = re.compile(r'(?P<k>[\w\-]+)="(?P<v>[^"]*)"')

def parse_attrs(s):
    return {m.group("k"): m.group("v") for m in ATTR_RE.finditer(s)}

def parse_m3u(text):
    out = []
    last = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line: continue
        if line.startswith("#EXTINF"):
            m = EXTINF_RE.match(line)
            if m:
                attrs = parse_attrs(m.group("attrs") or "")
                last = {
                    "name": (m.group("name") or "").strip(),
                    "logo": attrs.get("tvg-logo", ""),
                    "group": attrs.get("group-title", ""),
                }
            continue
        if line.startswith("#"): continue
        if last is None: continue
        out.append({**last, "url": line})
        last = None
    return out

def classify(entry):
    """Re-derive country + category from group-title (format: 'Country | Category')."""
    g = entry.get("group", "")
    country, category = "International", "General"
    if "|" in g:
        parts = [p.strip() for p in g.split("|")]
        if len(parts) == 2:
            country, category = parts[0], parts[1]
    return country, category

def main():
    with open(SRC, "r", encoding="utf-8") as f:
        text = f.read()
    entries = parse_m3u(text)
    print(f"loaded {len(entries)} entries")

    # group by (country, category, normalized_name) to dedupe
    def norm(name):
        # strip resolution + parenthetical
        s = re.sub(r'\s*\([^)]*\)\s*', '', name)
        s = re.sub(r'\s*(1080p|720p|576p|480p|4k|hd|fhd)\b', '', s, flags=re.I)
        return re.sub(r'\s+', ' ', s).strip().lower()

    groups = {}
    for e in entries:
        country, category = classify(e)
        key = (country, category, norm(e["name"]))
        if not key[2]: continue
        score = quality_score(e["url"], e["name"])
        prev = groups.get(key)
        if prev is None or score > prev[0]:
            groups[key] = (score, e)

    # build per-(country, category) buckets
    buckets = {}
    for (country, category, _), (_, e) in groups.items():
        buckets.setdefault((country, category), []).append(e)

    # sort + cap
    curated = []
    for (country, category), items in buckets.items():
        cap = CAPS.get(category, 30)
        items.sort(key=lambda e: (-quality_score(e["url"], e["name"]),
                                  COUNTRY_ORDER.get(country, 99),
                                  e["name"].lower()))
        for e in items[:cap]:
            curated.append({
                "id": f"{country.lower()}-{category.lower()}-{norm(e['name'])[:40]}-{len(curated)}".replace(" ", "-"),
                "name": e["name"],
                "logo": e.get("logo", ""),
                "url": e["url"],
                "country": country,
                "category": category,
            })

    print(f"curated {len(curated)} streams")

    # emit TypeScript
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/build_iptv_backend.py\n")
        f.write("// Curated, deduplicated, working-only IPTV streams.\n")
        f.write("// Source: iptv-org.github.io + extras, validated 2026-10-20.\n")
        f.write("// One entry per channel (best quality wins). No duplicates across sources.\n\n")
        f.write("export interface IptvChannel {\n")
        f.write("  id: string;\n")
        f.write("  name: string;\n")
        f.write("  logo: string;\n")
        f.write("  url: string;\n")
        f.write("  country: 'Bangladesh' | 'India' | 'International';\n")
        f.write("  category: string;\n")
        f.write("}\n\n")
        f.write("export const IPTV_CHANNELS: IptvChannel[] = ")
        f.write(json.dumps(curated, indent=2, ensure_ascii=False))
        f.write(";\n\n")
        f.write("export const IPTV_COUNTRIES = ['Bangladesh', 'India', 'International'] as const;\n")
        f.write("export const IPTV_CATEGORIES = Array.from(new Set(IPTV_CHANNELS.map(c => c.category))).sort();\n")

    print(f"wrote {OUT}")
    # also write a stats summary
    from collections import Counter
    by_cat = Counter(c["category"] for c in curated)
    by_country = Counter(c["country"] for c in curated)
    print("by category:", dict(by_cat))
    print("by country:", dict(by_country))

if __name__ == "__main__":
    main()
