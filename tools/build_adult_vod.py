#!/usr/bin/env python3
"""
Scrape public xvideos listing pages for real adult VOD titles.

Output: src/data/adult_vod.ts with real titles + thumbnails + embed URLs.
Each entry has the xvideos embed URL which plays the full video in a WebView.

Search terms cover Indian / Bangladeshi / desi / aunty / bhabhi / hindi / tamil
etc, plus a few general categories.
"""
import json
import re
import sys
import time
import urllib.parse
import urllib.request

UA = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) Chrome/120 Safari/535.3"}

# Indian/BD-flavored search terms + general adult categories
SEARCHES = [
    "bangladeshi", "indian", "desi", "hindi", "bhabhi", "aunty",
    "tamil", "mallu", "bengali", "pakistani", "south+indian",
    "amateur", "hardcore", "teen", "asian", "college",
]

# regex: data-id → data-src (thumbnail) → title (within ~1500 chars)
CARD_RE = re.compile(
    r'data-id="(?P<id>\d+)".*?data-src="(?P<thumb>[^"]+)".*?title="(?P<title>[^"]{5,150})"',
    re.DOTALL,
)

def tint_for(name):
    h = sum(ord(c) for c in name) % 8
    return ["#4A0F12","#4A1030","#1E3320","#6B2A1A","#5A1F10","#1A1F2A","#2A1A1A","#4A3A1F"][h]

def http_get(url, timeout=15):
    try:
        req = urllib.request.Request(url, headers=UA)
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.read().decode("utf-8", "replace")
    except Exception as e:
        return ""

def html_unescape(s):
    return (s.replace("&#039;", "'")
             .replace("&amp;", "&")
             .replace("&quot;", '"')
             .replace("&lt;", "<")
             .replace("&gt;", ">"))

def parse_page(html):
    out = []
    for m in CARD_RE.finditer(html):
        vid = m.group("id")
        thumb = m.group("thumb")
        title = html_unescape(m.group("title"))
        # Clean up title
        title = re.sub(r"\s+", " ", title).strip()
        # Skip very short or empty titles
        if len(title) < 3: continue
        out.append({
            "id":           f"xv-{vid}",
            "xv_id":        vid,
            "name":         title,
            "logo":         thumb,
            "url":          f"https://www.xvideos.com/embedframe/{vid}",
            "kind":         "embed",
            "category":     "Adult",
        })
    return out

def dedupe(items):
    seen = set()
    out = []
    for it in items:
        if it["xv_id"] in seen: continue
        seen.add(it["xv_id"])
        out.append(it)
    return out

def main():
    print("[P] xvideos adult scraper starting", flush=True)
    all_items = []
    for term in SEARCHES:
        url = f"https://www.xvideos.com/?k={urllib.parse.quote(term)}"
        print(f"  + search: {term}", flush=True)
        html = http_get(url)
        if not html:
            print(f"    ! failed: {term}", flush=True)
            continue
        items = parse_page(html)
        print(f"    = {len(items)} entries", flush=True)
        all_items.extend(items)
        time.sleep(0.4)  # be polite

    unique = dedupe(all_items)
    # cap to 200 — keeps bundle reasonable
    unique = unique[:200]
    print(f"  = {len(unique)} unique adult VOD titles", flush=True)

    # build final title objects
    titles = []
    for i, v in enumerate(unique):
        titles.append({
            "id":           v["id"],
            "tmdb_id":      0,
            "name":         v["name"],
            "kind":         "movie",
            "year":         2024,
            "maturity":     "18+",
            "runtime":      0,
            "seasons":      [],
            "genres":       ["Adult", "18+"],
            "moods":        ["Adult", "Streaming"],
            "synopsis":     f"Adult video: {v['name']}",
            "cast":         [],
            "creators":     [],
            "original":     False,
            "seed":         v["id"],
            "tint":         tint_for(v["name"]),
            "video":        v["url"],                                # primary embed URL
            "streams":     [{"name": "xvideos", "url": v["url"], "kind": "embed"}],
            "quality":      ["HD"],
            "category":     "Adult",
            "poster":       v["logo"],
            "background":   v["logo"],
            "imdbRating":   "",
        })

    out = sys.argv[1] if len(sys.argv) > 1 else "/home/z/my-project/workspace/MythTube-main/src/data/adult_vod.ts"
    with open(out, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/build_adult_vod.py from public xvideos listing pages.\n")
        f.write("// Real adult VOD titles with thumbnails + embed URLs (WebView-playable).\n\n")
        f.write("import type { VodTitle } from './vod';\n\n")
        f.write("// Adult VOD titles — fully real, WebView-playable embeds.\n")
        f.write("export const ADULT_VOD_TITLES: VodTitle[] = ")
        f.write(json.dumps(titles, indent=2, ensure_ascii=False))
        f.write(";\n\n")
        f.write("export function adultVodTitles(limit = 30): VodTitle[] {\n")
        f.write("  return ADULT_VOD_TITLES.slice(0, limit);\n}\n")

    print(f"wrote {out}", flush=True)
    print(f"by category: {{'Adult': {len(titles)}}}", flush=True)

if __name__ == "__main__":
    main()
